#ifndef _BOARD_CONFIG_H_
#define _BOARD_CONFIG_H_

#include <driver/gpio.h>

#define AUDIO_INPUT_SAMPLE_RATE  16000
#define AUDIO_OUTPUT_SAMPLE_RATE 24000

// 麦克风与功放各用一组独立 I2S 时钟（INMP441 + MAX98357）
#define AUDIO_I2S_METHOD_SIMPLEX

#define AUDIO_I2S_MIC_GPIO_WS   GPIO_NUM_4
#define AUDIO_I2S_MIC_GPIO_SCK  GPIO_NUM_5
#define AUDIO_I2S_MIC_GPIO_DIN  GPIO_NUM_6
#define AUDIO_I2S_SPK_GPIO_DOUT GPIO_NUM_7
#define AUDIO_I2S_SPK_GPIO_BCLK GPIO_NUM_15
#define AUDIO_I2S_SPK_GPIO_LRCK GPIO_NUM_16

#define BUILTIN_LED_GPIO        GPIO_NUM_48
#define BOOT_BUTTON_GPIO        GPIO_NUM_0
#define TOUCH_BUTTON_GPIO       GPIO_NUM_NC
#define VOLUME_UP_BUTTON_GPIO   GPIO_NUM_NC
#define VOLUME_DOWN_BUTTON_GPIO GPIO_NUM_NC

// ST7789 240x240 四线 SPI（底板 8P 母座）
#define DISPLAY_BACKLIGHT_PIN GPIO_NUM_42
#define DISPLAY_MOSI_PIN      GPIO_NUM_47
#define DISPLAY_CLK_PIN       GPIO_NUM_21
#define DISPLAY_DC_PIN        GPIO_NUM_40
#define DISPLAY_RST_PIN       GPIO_NUM_45
#define DISPLAY_CS_PIN        GPIO_NUM_41

#define DISPLAY_WIDTH   240
#define DISPLAY_HEIGHT  240
#define DISPLAY_MIRROR_X false
#define DISPLAY_MIRROR_Y false
#define DISPLAY_SWAP_XY false
#define DISPLAY_INVERT_COLOR    true
#define DISPLAY_RGB_ORDER  LCD_RGB_ELEMENT_ORDER_RGB
#define DISPLAY_OFFSET_X  0
#define DISPLAY_OFFSET_Y  0
#define DISPLAY_BACKLIGHT_OUTPUT_INVERT false
#define DISPLAY_SPI_MODE 0

// 传感器 I2C 总线：AHT20 / BMP280 / MPU6050 共用，注意不要和屏幕引脚混用
#define SENSOR_I2C_SDA_PIN GPIO_NUM_8
#define SENSOR_I2C_SCL_PIN GPIO_NUM_9
#define SENSOR_I2C_FREQ    400000

// ML307R Cat.1 模组（模组侧命名，ESP 侧 TX=12、RX=11），固件默认 115200
#define ML307_TX_PIN   GPIO_NUM_12
#define ML307_RX_PIN   GPIO_NUM_11
#define ML307_BAUD_RATE 115200

// ATGM336H GPS：默认接在 GPIO43/44，与 UART0 控制台冲突，
// 因此只有在 CONFIG_GOOUUU_GPS_ENABLE 打开时才启用（控制台需改 USB-Serial-JTAG）
#define GPS_UART_NUM 2
#define GPS_TX_PIN   GPIO_NUM_43
#define GPS_RX_PIN   GPIO_NUM_44
#define GPS_BAUD_RATE 9600

#endif  // _BOARD_CONFIG_H_
